/**
 * Phase 12 E2E Test Suite 3: Owner Dashboard & Administration E2E
 * Tests owner authentication, 4 metric clusters, user search,
 * review moderation, submission review, ticket closure, audit logging,
 * and foreign key consistency.
 */
const { spawn } = require('child_process');
const path = require('path');
const { dbAsync } = require('../../server/db/connection.cjs');

const PORT = 3006;
const BASE_URL = `http://127.0.0.1:${PORT}`;
let serverProcess = null;

function assert(condition, message) {
    if (!condition) {
        console.error(`[FAIL] ${message}`);
        throw new Error(message);
    }
    console.log(`[PASS] ${message}`);
}

async function startServer() {
    return new Promise((resolve, reject) => {
        serverProcess = spawn('node', ['server/index.cjs'], {
            cwd: path.resolve(__dirname, '../../'),
            env: { ...process.env, PORT: String(PORT) }
        });

        let started = false;
        serverProcess.stdout.on('data', d => {
            const out = d.toString();
            if (out.includes('listening on')) {
                started = true;
                resolve();
            }
        });

        serverProcess.stderr.on('data', d => {
            const errStr = d.toString().trim();
            if (errStr && !errStr.includes('ExperimentalWarning')) {
                console.error('[SERVER_LOG]', errStr);
            }
        });

        serverProcess.on('error', reject);
        setTimeout(() => {
            if (!started) reject(new Error('Server startup timed out'));
        }, 10000);
    });
}

function stopServer() {
    if (serverProcess) {
        serverProcess.kill();
        serverProcess = null;
    }
}

async function cleanupTestData(usernames = ['e2e_p12_submitter']) {
    for (const u of usernames) {
        const row = await dbAsync.get('SELECT id FROM users WHERE username = ?', [u]);
        if (!row) continue;
        const uid = row.id;

        await dbAsync.run('DELETE FROM ticket_messages WHERE sender_user_id = ?', [uid]);
        await dbAsync.run('DELETE FROM support_tickets WHERE user_id = ?', [uid]);
        await dbAsync.run('DELETE FROM submissions WHERE user_id = ?', [uid]);
        await dbAsync.run('DELETE FROM reviews WHERE user_id = ?', [uid]);
        await dbAsync.run('DELETE FROM audit_logs WHERE actor_id = ?', [uid]);
        await dbAsync.run('DELETE FROM sessions WHERE user_id = ?', [uid]);
        await dbAsync.run('DELETE FROM user_profiles WHERE user_id = ?', [uid]);
        await dbAsync.run('DELETE FROM users WHERE id = ?', [uid]);
    }
    // Clean up test audit logs generated by owner during test
    await dbAsync.run("DELETE FROM audit_logs WHERE metadata LIKE '%test-p12%' OR metadata LIKE '%e2e_p12%'");
}

async function run() {
    console.log('=== PHASE 12: OWNER DASHBOARD & ADMINISTRATION E2E TEST ===');
    await startServer();
    console.log('[SERVER] Running on', BASE_URL);

    const SUBMITTER = { username: 'e2e_p12_submitter', email: 'submitter@test.local', password: 'Password123!', confirmPassword: 'Password123!', displayName: 'Test Submitter' };

    try {
        await cleanupTestData([SUBMITTER.username]);

        // 1. Owner Login
        let ownerPass = 'changeme123';
        let ownerLoginRes = await fetch(`${BASE_URL}/api/auth/login`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ username: 'owner', password: ownerPass })
        });
        if (!ownerLoginRes.ok && process.env.OWNER_INITIAL_PASSWORD) {
            ownerPass = process.env.OWNER_INITIAL_PASSWORD;
            ownerLoginRes = await fetch(`${BASE_URL}/api/auth/login`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ username: 'owner', password: ownerPass })
            });
        }
        assert(ownerLoginRes.ok, 'Owner logged in successfully');
        const ownerCookie = ownerLoginRes.headers.get('set-cookie');
        assert(!!ownerCookie, 'Owner received session cookie');

        // 2. Fetch 4 Metric Clusters
        const statsRes = await fetch(`${BASE_URL}/api/owner/stats`, {
            headers: { 'Cookie': ownerCookie }
        });
        assert(statsRes.ok, 'Owner fetched /api/owner/stats');
        const stats = await statsRes.json();
        
        // Assert Platform Cluster
        assert(typeof stats.platform.totalUsers === 'number', 'Platform cluster has totalUsers');
        assert(typeof stats.platform.onlineUsers === 'number', 'Platform cluster has onlineUsers');
        assert(typeof stats.platform.pendingSubmissions === 'number', 'Platform cluster has pendingSubmissions');
        assert(typeof stats.platform.openTickets === 'number', 'Platform cluster has openTickets');

        // Assert Content Cluster
        assert(typeof stats.content.publishedGames === 'number', 'Content cluster has publishedGames');
        assert(typeof stats.content.publishedConsoles === 'number', 'Content cluster has publishedConsoles');
        assert(typeof stats.content.publishedStories === 'number', 'Content cluster has publishedStories');
        assert(typeof stats.content.publishedGuides === 'number', 'Content cluster has publishedGuides');
        assert(typeof stats.content.publishedNews === 'number', 'Content cluster has publishedNews');

        // Assert Community Cluster
        assert(typeof stats.community.totalComments === 'number', 'Community cluster has totalComments');
        assert(typeof stats.community.totalReviews === 'number', 'Community cluster has totalReviews');
        assert(typeof stats.community.pendingReports === 'number', 'Community cluster has pendingReports');
        assert(typeof stats.community.totalFriendships === 'number', 'Community cluster has totalFriendships');

        // Assert System Cluster
        assert(typeof stats.system.databaseSize === 'string', 'System cluster has databaseSize string');
        assert(stats.system.walMode === 'WAL', `System cluster journal mode is WAL (got ${stats.system.walMode})`);
        assert(typeof stats.system.searchIndexCount === 'number', 'System cluster has searchIndexCount');
        assert(typeof stats.system.mediaCount === 'number', 'System cluster has mediaCount');

        // 3. Register a test user for administrative interactions
        const userReg = await fetch(`${BASE_URL}/api/auth/signup`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(SUBMITTER)
        });
        assert(userReg.ok, 'Test submitter user registered');
        const userCookie = userReg.headers.get('set-cookie');

        // 4. Test User Search
        const searchUserRes = await fetch(`${BASE_URL}/api/owner/users?q=submitter`, {
            headers: { 'Cookie': ownerCookie }
        });
        assert(searchUserRes.ok, 'Owner searched users with query');
        const searchUserData = await searchUserRes.json();
        const found = searchUserData.users.find(u => u.username === SUBMITTER.username);
        assert(!!found, 'Owner search returned matching user');
        assert(found.email === SUBMITTER.email, 'Owner search returned email');

        // 5. Test Review Moderation & Audit Logging
        // Post review as test user
        const gamesRes = await fetch(`${BASE_URL}/api/content/games?limit=1`);
        const gamesData = await gamesRes.json();
        const testGame = gamesData.games[0];

        const revPost = await fetch(`${BASE_URL}/api/community/reviews`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json', 'Cookie': userCookie },
            body: JSON.stringify({
                target_type: 'GAME',
                target_id: testGame.id,
                rating: 6,
                title: 'Review for Moderation Test',
                body: 'Testing owner review moderation deletion flow.'
            })
        });
        assert(revPost.ok, 'User posted review for moderation test');
        const revData = await revPost.json();
        const reviewId = revData.id;

        // Owner deletes review
        const revDel = await fetch(`${BASE_URL}/api/owner/reviews/${reviewId}/delete`, {
            method: 'POST',
            headers: { 'Cookie': ownerCookie }
        });
        assert(revDel.ok, 'Owner deleted/rejected review');

        // Verify review status is REJECTED in database
        const dbRev = await dbAsync.get('SELECT status FROM reviews WHERE id = ?', [reviewId]);
        assert(dbRev.status === 'REJECTED', 'Review status updated to REJECTED');

        // 6. Test Support Ticket Closure
        const ticketCreate = await fetch(`${BASE_URL}/api/support/tickets`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json', 'Cookie': userCookie },
            body: JSON.stringify({
                subject: 'Need help with save data',
                category: 'TECHNICAL',
                priority: 'LOW',
                message: 'My retro save states are not synchronizing.'
            })
        });
        assert(ticketCreate.ok, 'User created support ticket');
        const ticketData = await ticketCreate.json();
        const ticketId = ticketData.ticket_id || ticketData.id || (ticketData.ticket && ticketData.ticket.id);

        const ticketClose = await fetch(`${BASE_URL}/api/owner/tickets/${ticketId}/close`, {
            method: 'POST',
            headers: { 'Cookie': ownerCookie }
        });
        assert(ticketClose.ok, 'Owner closed support ticket');

        const dbTicket = await dbAsync.get('SELECT status FROM support_tickets WHERE id = ?', [ticketId]);
        assert(dbTicket.status === 'CLOSED', 'Support ticket status is CLOSED');

        // 7. Verify Audit Log contains entries
        const auditRes = await fetch(`${BASE_URL}/api/owner/audit-logs`, {
            headers: { 'Cookie': ownerCookie }
        });
        assert(auditRes.ok, 'Owner fetched audit logs');
        const auditData = await auditRes.json();
        assert(Array.isArray(auditData.logs) && auditData.logs.length > 0, 'Audit logs contains recorded actions');
        const revLog = auditData.logs.find(l => l.action === 'DELETE_REVIEW' && l.entity_id === reviewId);
        assert(!!revLog, 'Audit log contains entry for DELETE_REVIEW');
        const ticketLog = auditData.logs.find(l => l.action === 'CLOSE_TICKET' && l.entity_id === ticketId);
        assert(!!ticketLog, 'Audit log contains entry for CLOSE_TICKET');

        console.log('[SUCCESS] All Owner Dashboard & Administration E2E assertions passed cleanly!');
    } finally {
        await cleanupTestData([SUBMITTER.username]);
        stopServer();

        const fkCheck = await dbAsync.all('PRAGMA foreign_key_check');
        assert(fkCheck.length === 0, `Database has 0 foreign key violations after test (found ${fkCheck.length})`);
    }
}

run().catch(err => {
    console.error('[FATAL]', err);
    stopServer();
    process.exit(1);
});
